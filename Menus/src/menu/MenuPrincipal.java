    private void subMenuErrorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_subMenuErrorActionPerformed
        // TODO add your handling code here:
        int resultado = JOptionPane.showConfirmDialog(this, "Confirmacion de ventanas", "Ventanas", JOptionPane.OK_CANCEL_OPTION);
        
        if(resultado == JOptionPane.OK_OPTION){
        
        jPanel.setBackground(Color.GREEN);
        }else if(resultado == JOptionPane.CANCEL_OPTION){
        jPanel.setBackground(Color.DARK_GRAY);
        }else{
        jPanel.setBackground(Color.MAGENTA);}
    }//GEN-LAST:event_subMenuErrorActionPerformed

