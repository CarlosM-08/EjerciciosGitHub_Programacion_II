    private void jToggleBloqueoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jToggleBloqueoActionPerformed
        // TODO add your handling code here:
        Color valorInicio = Color.YELLOW;
        Color valorFinal = Color.GREEN;
        
        if (jToggleBloqueo.isSelected()){
            jToggleBloqueo.setText("Bloqueado");
        jToggleBloqueo.setBackground(valorFinal);
        jTextNombre.setEnabled(false);
        jTextApellido.setEnabled(false);
        
        }
        else{
            jToggleBloqueo.setText("Desbloqueado");
        jToggleBloqueo.setBackground(valorInicio);
        jTextNombre.setEnabled(false);
        jTextApellido.setEnabled(false);
        }
    }//GEN-LAST:event_jToggleBloqueoActionPerformed

